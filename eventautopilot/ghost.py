"""WP3 · Ghost newsletter draft.

DRAFT ONLY: this module creates/updates posts with status="draft". It never
publishes a post and never triggers a newsletter email send. A human approves
and sends from the Ghost admin.
"""
from __future__ import annotations

import html
import json
import re
import sys
import time
from pathlib import Path

import httpx
import jwt

from . import config
from .models import RunResult

STATE_FILE = config.OUT / "ghost_state.json"
API_VERSION = "v5.0"


def make_token(key: str, now: int | None = None) -> str:
    """Short-lived Ghost Admin API JWT from an 'id:secret' key."""
    kid, secret = key.split(":", 1)
    iat = int(now if now is not None else time.time())
    return jwt.encode(
        {"iat": iat, "exp": iat + 5 * 60, "aud": "/admin/"},
        bytes.fromhex(secret),
        algorithm="HS256",
        headers={"kid": kid, "alg": "HS256", "typ": "JWT"},
    )


def _excerpt(text: str, limit: int = 300) -> str:
    text = re.sub(r"<[^>]+>", " ", text or "")
    text = re.sub(r"[#*_>`]+", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) <= limit:
        return text
    return text[: limit - 1].rsplit(" ", 1)[0].rstrip(",.;:") + "…"


def _load_state() -> dict:
    try:
        return json.loads(STATE_FILE.read_text())
    except Exception:
        return {}


def _save_state(state: dict) -> None:
    try:
        STATE_FILE.write_text(json.dumps(state, indent=2))
    except Exception:
        pass


def write_preview(result: RunResult, feature_image: str = "") -> Path | None:
    """Standalone email-like preview at out/newsletter_{id}.html (no keys needed)."""
    try:
        spec, art = result.spec, result.artifacts
        sid = spec.id or "event"
        subject = art.newsletter_subject or spec.title or "Newsletter"
        img = feature_image or spec.cover_url
        hero = (
            f'<img src="{html.escape(img)}" alt="" style="width:100%;display:block;border-radius:8px 8px 0 0">'
            if img.startswith(("http://", "https://")) else ""
        )
        cta = (
            f'<p style="text-align:center;margin:28px 0"><a href="{html.escape(spec.luma_url)}" '
            'style="background:#111;color:#fff;padding:12px 22px;border-radius:6px;text-decoration:none;'
            'font-weight:600">RSVP on Luma</a></p>' if spec.luma_url else ""
        )
        body = art.newsletter_html or f"<p>{html.escape(art.page_copy or spec.description)}</p>"
        doc = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(subject)}</title>
<style>
body{{margin:0;background:#f2f2f0;font:16px/1.6 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,sans-serif;color:#222}}
.wrap{{max-width:600px;margin:32px auto;background:#fff;border-radius:8px;box-shadow:0 1px 4px rgba(0,0,0,.08)}}
.inner{{padding:28px 32px}} h1{{font-size:26px;line-height:1.25;margin:0 0 6px}}
.meta{{color:#777;font-size:13px;margin-bottom:20px}} a{{color:#0b6bcb}}
.badge{{display:inline-block;background:#fff3cd;color:#7a5a00;font-size:12px;padding:2px 8px;border-radius:4px;margin-bottom:12px}}
.foot{{color:#999;font-size:12px;text-align:center;padding:0 0 24px}}
</style></head><body>
<div class="wrap">{hero}<div class="inner">
<span class="badge">DRAFT preview, not sent</span>
<h1>{html.escape(subject)}</h1>
<div class="meta">{html.escape(spec.title)}{" · " + html.escape(spec.venue.name) if spec.venue.name else ""}{" · " + spec.date.strftime("%a %d %b %Y") if spec.date else ""}</div>
{body}
{cta}
</div></div>
<div class="foot">Generated by EventAutopilot · draft only</div>
</body></html>"""
        path = config.OUT / f"newsletter_{sid}.html"
        path.write_text(doc)
        return path
    except Exception as e:
        print(f"ghost: preview failed ({e})")
        return None


def _fail(resp: httpx.Response) -> str:
    try:
        msg = resp.json()["errors"][0].get("message", "")
    except Exception:
        msg = resp.text[:120]
    print(f"ghost: failed ({resp.status_code} {msg[:120]})")
    return ""


def create_draft(result: RunResult, feature_image: str = "") -> str:
    """Create (or update) a Ghost DRAFT for this event; return its admin editor URL or ""."""
    write_preview(result, feature_image)
    if not config.HAS_GHOST:
        print("ghost: skipped (no key)")
        return ""
    try:
        spec, art = result.spec, result.artifacts
        base = config.GHOST_ADMIN_URL
        api = f"{base}/ghost/api/admin/posts/"
        headers = {
            "Authorization": f"Ghost {make_token(config.GHOST_ADMIN_KEY)}",
            "Accept-Version": API_VERSION,
        }
        post: dict = {
            "title": art.newsletter_subject or spec.title or "Event newsletter",
            "html": art.newsletter_html or f"<p>{html.escape(art.page_copy)}</p>",
            # DRAFT ONLY. Never set "published"/"scheduled", never pass ?newsletter= (that emails subscribers).
            "status": "draft",
            "custom_excerpt": _excerpt(art.page_copy or spec.description),
            "tags": [{"name": "event"}],
        }
        if feature_image.startswith(("http://", "https://")):
            post["feature_image"] = feature_image

        state = _load_state()
        key = spec.id or spec.title
        prev = state.get(key)
        with httpx.Client(timeout=20, headers=headers) as c:
            resp = None
            if prev and prev.get("id"):
                # Ghost needs the current updated_at for collision detection on PUT.
                g = c.get(f"{api}{prev['id']}/")
                if g.status_code == 200:
                    cur = g.json()["posts"][0]
                    if cur.get("status") != "draft":
                        # Already published by a human: leave it alone, make a fresh draft.
                        prev = None
                    else:
                        post["updated_at"] = cur["updated_at"]
                        resp = c.put(f"{api}{prev['id']}/?source=html", json={"posts": [post]})
                elif g.status_code == 404:
                    prev = None
                else:
                    return _fail(g)
            if resp is None:
                resp = c.post(f"{api}?source=html", json={"posts": [post]})
        if resp.status_code not in (200, 201):
            return _fail(resp)
        saved = resp.json()["posts"][0]
        state[key] = {"id": saved["id"], "updated_at": saved.get("updated_at", "")}
        _save_state(state)
        url = f"{base}/ghost/#/editor/post/{saved['id']}"
        print(f"ghost: draft {'updated' if prev else 'created'} {url}")
        return url
    except Exception as e:
        print(f"ghost: failed (error {str(e)[:120]})")
        return ""


if __name__ == "__main__":
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else config.ROOT / "seed" / "sample_run.json"
    rr = RunResult.model_validate_json(src.read_text())
    url = create_draft(rr)
    print(f"preview: {write_preview(rr)}")
    print(f"result: {url!r}")
